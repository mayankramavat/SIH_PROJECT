"""
Forecast API Endpoints (SIH_26246)
----------------------------------
REST endpoints for multi-horizon AI/ML demand forecasting and forecast summary.
"""
from typing import List, Optional
from fastapi import APIRouter, Query, HTTPException, status
from backend.app.database.schemas import ForecastRecord, ForecastSummaryRecord
from backend.app.services.forecast_service import (
    get_forecast_data,
    get_forecast_summary_data,
    get_model_evaluation_data
)

router = APIRouter(prefix="/forecast", tags=["Forecast"])


@router.get(
    "",
    response_model=List[ForecastRecord],
    summary="Get multi-month demand forecasts",
    description="Retrieve demand forecasts generated by ML models. Supported horizon values: 3, 6, 12."
)
def read_forecast(
    state: Optional[str] = Query(None, description="Filter by state name"),
    district: Optional[str] = Query(None, description="Filter by district name"),
    trade: Optional[str] = Query(None, description="Filter by trade name"),
    horizon: Optional[int] = Query(None, description="Forecast horizon in months: 3, 6, or 12")
):
    """Retrieve predicted demand records for the selected horizon and geography."""
    if horizon is not None and horizon not in (3, 6, 12):
        raise HTTPException(
            status_code=status.HTTP_400_BAD_REQUEST,
            detail=f"Invalid forecast horizon '{horizon}'. Supported horizons are 3, 6, and 12."
        )

    try:
        records = get_forecast_data(
            state=state,
            district=district,
            trade=trade,
            horizon=horizon
        )
        return records
    except HTTPException:
        raise
    except Exception as exc:
        raise HTTPException(
            status_code=status.HTTP_500_INTERNAL_SERVER_ERROR,
            detail=f"Error retrieving forecast records: {str(exc)}"
        )


@router.get(
    "/summary",
    response_model=List[ForecastSummaryRecord],
    summary="Get 3/6/12 month forecast summary & future gap metrics",
    description="Returns consolidated view of baseline demand, future predicted demand (3m/6m/12m), supply, and warning levels."
)
def read_forecast_summary(
    state: Optional[str] = Query(None, description="Filter by state name"),
    district: Optional[str] = Query(None, description="Filter by district name"),
    trade: Optional[str] = Query(None, description="Filter by trade name")
):
    """Retrieve consolidated multi-horizon forecast summary."""
    try:
        records = get_forecast_summary_data(
            state=state,
            district=district,
            trade=trade
        )
        return records
    except HTTPException:
        raise
    except Exception as exc:
        raise HTTPException(
            status_code=status.HTTP_500_INTERNAL_SERVER_ERROR,
            detail=f"Error retrieving forecast summary: {str(exc)}"
        )


@router.get(
    "/evaluation",
    summary="Get ML model evaluation metrics",
    description="Returns empirical validation metrics (MAE, RMSE, R2, test period) for baseline and ML forecaster."
)
def read_model_evaluation():
    """Retrieve model benchmark evaluation metrics."""
    try:
        return get_model_evaluation_data()
    except Exception as exc:
        raise HTTPException(
            status_code=status.HTTP_500_INTERNAL_SERVER_ERROR,
            detail=f"Error retrieving model evaluation metrics: {str(exc)}"
        )
